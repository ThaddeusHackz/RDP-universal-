#!/usr/bin/env bash
# THADD OS · shell bundler.
#   js/kernel.js (+ 20 modules) --esbuild--> desktop/dist/thadd-shell.js
# A single classic <script> means the shell runs from file://, from a local
# server, or inside the live ISO with zero module/CORS requirements.
# The bundle is committed so an ISO build needs no npm; regenerate with this.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
mkdir -p desktop/dist
if [ ! -d tools/tests/node_modules/esbuild ]; then
  echo "› installing esbuild (tools/tests)"; (cd tools/tests && npm install --silent --no-fund --no-audit esbuild >/dev/null)
fi
node --input-type=module -e '
import { build } from "./tools/tests/node_modules/esbuild/lib/main.js";
const r = await build({
  entryPoints: ["desktop/js/kernel.js"], bundle: true, format: "iife",
  target: ["chrome100","firefox100","safari15"], outfile: "desktop/dist/thadd-shell.js",
  minify: false, sourcemap: false, legalComments: "none", charset: "utf8", logLevel: "warning",
});
if (r.errors.length) { console.error(r.errors); process.exit(1); }
'
node --input-type=module -e '
import { readFileSync, writeFileSync, statSync } from "fs";
const js = readFileSync("desktop/dist/thadd-shell.js", "utf8");
const html = readFileSync("desktop/index.html", "utf8")
  .replace(/<script type="module" src="js\/kernel\.js"><\/script>/,
           `<script src="dist/thadd-shell.js"></script>`)
  .replace("</title>", "</title>\n<!-- generated by tools/build-shell.sh — do not edit -->");
writeFileSync("desktop/shell.html", html);
const kb = (statSync("desktop/dist/thadd-shell.js").size / 1024).toFixed(0);
console.log(`✅ shell bundle: desktop/dist/thadd-shell.js (${kb} KiB) + desktop/shell.html`);
'
